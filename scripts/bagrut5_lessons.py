def _one(text: str) -> str:
    return " ".join(text.split())


# topic id -> (explanation, worked example)
LESSONS: dict[str, tuple[str, str]] = {}


def _put(tid: str, explanation: str, worked: str) -> None:
    LESSONS[tid] = (_one(explanation), _one(worked))


