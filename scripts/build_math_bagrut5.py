def _emit_level(prefix: str, level: int, learn: tuple[str, str, str], practices: list[dict], check: dict) -> tuple[dict, list[dict]]:
    title, body, can = learn
    nodes = [_learn(f"{prefix}_l{level}_learn", title, body, can)]
    for i, spec in enumerate(practices, 1):
        nodes.append(_mc(
            f"{prefix}_l{level}_p{i}",
            "practice",
            spec["title"],
            spec["stem"],
            spec["answer"],
            spec["wrongs"],
            spec["hint"],
            spec["method"],
            spec["can_do"],
        ))
    nodes.append(_mc(
        f"{prefix}_l{level}_check",
        "check",
        check["title"],
        check["stem"],
        check["answer"],
        check["wrongs"],
        check["hint"],
        check["method"],
        check["can_do"],
    ))
    he = {1: "רמה 1, בסיס", 2: "רמה 2, יישום", 3: "רמה 3, שליטה"}[level]
    en = {1: "Level 1, basics", 2: "Level 2, application", 3: "Level 3, mastery"}[level]
    ar = {1: "المستوى 1", 2: "المستوى 2", 3: "المستوى 3"}[level]
    topic = _topic(f"{prefix}_l{level}", he, en, ar, nodes)
    return topic, nodes


def _emit_review(prefix: str, items: list[dict]) -> tuple[dict, list[dict]]:
    earlier = [f"{prefix}_l1", f"{prefix}_l2", f"{prefix}_l3"]
    nodes = []
    for i, spec in enumerate(items, 1):
        nodes.append(_mc(
            f"{prefix}_rev_{i}",
            "practice",
            spec["title"],
            spec["stem"],
            spec["answer"],
            spec["wrongs"],
            spec["hint"],
            spec["method"],
            spec["can_do"],
            review=earlier,
        ))
    topic = _topic(f"{prefix}_review", "חזרה מעורבת", "Mixed review", "مراجعة مختلطة", nodes)
    return topic, nodes


def _stage_path(slug: str, he: str, en: str, ar: str, emoji: str, blurb: tuple[str, str, str], prefix: str, learn_key: str, packs, prereq: str) -> dict:
    topics: list[dict] = []
    nodes: list[dict] = []
    for level in (1, 2, 3):
        practices, check = packs[level - 1]
        practices = [*practices, *extras_for(learn_key, level)]
        topic, built = _emit_level(prefix, level, LEARNS[learn_key][level - 1], practices, check)
        topics.append(topic)
        nodes.extend(built)
    topic, built = _emit_review(prefix, reviews_for(learn_key))
    topics.append(topic)
    nodes.extend(built)
    return _path(slug, he, en, ar, blurb[0], blurb[1], blurb[2], emoji, [prereq], topics, nodes)


