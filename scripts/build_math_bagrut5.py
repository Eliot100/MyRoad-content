def main() -> None:
    placement = placement_path()
    roads, last = teaching_paths(placement["id"])
    exam = exam_path(last)
    docs = [placement, *roads, exam]
    ids = [d["id"] for d in docs]
    if ids != [f"path_math_bagrut5_{row[0]}" for row in SERIES]:
        raise SystemExit(f"id order mismatch: {ids}")
    # Chain: each teaching road and the exam depend only on the previous one.
    for i, doc in enumerate(docs):
        if i == 0:
            if doc["prerequisite_path_ids"]:
                raise SystemExit("placement must not have a prerequisite")
        else:
            if doc["prerequisite_path_ids"] != [docs[i - 1]["id"]]:
                raise SystemExit(f"bad prerequisite on {doc['id']}")
    stems: dict[str, str] = {}
    dupes: list[str] = []
    for doc in docs:
        for node in doc["nodes"]:
            if node.get("type") not in ("practice", "check"):
                continue
            stem = node.get("body_he") or ""
            if stem in stems:
                dupes.append(f"{doc['id']} repeats {stems[stem]}: {stem}")
            else:
                stems[stem] = doc["id"]
            if not node.get("hint") or not node.get("worked_method") or not node.get("can_do"):
                raise SystemExit(f"{doc['id']} {node['id']} is missing a method")
    if dupes:
        raise SystemExit("repeated questions:\n" + "\n".join(dupes[:30]))
    for doc in roads:
        for level in (1, 2, 3):
            count = sum(1 for node in doc["nodes"] if re.search(rf"_l{level}_p\d+$", node["id"]))
            if count < 12:
                raise SystemExit(f"{doc['id']} level {level} has only {count} practices")
        reviews = sum(1 for node in doc["nodes"] if node.get("kind") == "review")
        if reviews < 6:
            raise SystemExit(f"{doc['id']} has only {reviews} review items")
    OUT.mkdir(parents=True, exist_ok=True)
    # Remove stale math bagrut files so a renamed slug cannot linger.
    for old in OUT.glob("path_math_bagrut5_*.json"):
        old.unlink()
    for doc in docs:
        path = OUT / f"{doc['id']}.json"
        path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{doc['id']}: {len(doc['nodes'])} steps, {doc['estimated_minutes']} min")
    print(f"wrote {len(docs)} roads")


if __name__ == "__main__":
    main()
