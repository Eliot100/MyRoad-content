def _clean(text: str) -> str:
    if any(mark in text for mark in BAD):
        raise SystemExit(f"long dash in text: {text[:80]!r}")
    return text


def _signed(n: int) -> str:
    return f"+ {n}" if n > 0 else f"- {abs(n)}"


def _ax(a: int, var: str = "x") -> str:
    if a == 1:
        return var
    if a == -1:
        return f"-{var}"
    return f"{a}{var}"


def _poly_linear(a: int, b: int, var: str = "x") -> str:
    left = _ax(a, var)
    if b == 0:
        return left
    return f"{left} {_signed(b)}"


def _mc(
    nid: str,
    ntype: str,
    title: str,
    stem: str,
    answer: str,
    wrongs: list[str],
    hint: str,
    method: str,
    can_do: str,
    *,
    kind: str = "understanding",
    review: list[str] | None = None,
    area: str | None = None,
    difficulty: float | None = None,
) -> dict:
    labels: list[str] = []
    for raw in [answer, *wrongs]:
        label = _clean(str(raw).strip())
        if label and label not in labels:
            labels.append(label)
    seed = str(answer).strip()
    numeric = None
    try:
        numeric = int(seed)
    except ValueError:
        numeric = None
    step = 1
    while len(labels) < 4:
        if numeric is not None:
            extra = str(numeric + step)
            if extra == seed:
                step += 1
                continue
            step += 1
        elif "וגם" in seed:
            extra = ["אין פתרון", "פתרון יחיד", "אינסוף פתרונות", "0"][len(labels) - 1]
        else:
            extra = ["0", "1", "אין מספר כזה", "לא מוגדר"][len(labels) - 1]
        if extra not in labels:
            labels.append(extra)
    if labels[0] != seed:
        raise SystemExit(f"{nid}: answer {answer!r} missing from choices {labels}")
    order = labels[:4]
    rng = random.Random(nid)
    rng.shuffle(order)
    ids = ["a", "b", "c", "d"]
    correct = ids[order.index(str(answer).strip())]
    node: dict = {
        "id": nid,
        "type": ntype,
        "kind": kind,
        "title": _clean(title),
        "body_he": _clean(stem),
        "choices": [{"id": cid, "label": lab} for cid, lab in zip(ids, order)],
        "correct": correct,
        "hint": _clean(hint),
        "worked_method": _clean(method),
        "can_do": _clean(can_do),
        "feedback_ok": "נכון.",
        "feedback_try": _clean(hint),
    }
    if review:
        node["review_topic_ids"] = review
        node["kind"] = "review"
    if area is not None:
        node["area"] = area
    if difficulty is not None:
        node["difficulty"] = difficulty
    return node


def _learn(nid: str, title: str, body: str, can_do: str) -> dict:
    return {
        "id": nid,
        "type": "learn",
        "kind": "understanding",
        "title": _clean(title),
        "body_he": _clean(body),
        "can_do": _clean(can_do),
    }


def _topic(tid: str, he: str, en: str, ar: str, nodes: list[dict]) -> dict:
    return {
        "id": tid,
        "titles": {"he": he, "en": en, "ar": ar},
        "emoji": "▪️",
        "node_ids": [n["id"] for n in nodes],
    }


